CATEGORY_BY_KEY = {c.key: c for c in CATEGORIES}
CATEGORY_ORDER = {c.key: i for i, c in enumerate(CATEGORIES)}


def _compile() -> list[tuple[int, re.Pattern[str], str]]:
    rules: list[tuple[int, re.Pattern[str], str]] = []
    for category in CATEGORIES:
        for word in category.words:
            prefix = word.endswith("*")
            text = normalize(word.rstrip("*"))
            pattern = r"(?<!\w)" + re.escape(text) + ("" if prefix else r"(?!\w)")
            rules.append((len(text), re.compile(pattern), category.key))
    # Longest entry first so that "масло сливочное" beats "масло"; stable for ties.
    rules.sort(key=lambda rule: -rule[0])
    return rules


_RULES = _compile()


def guess_category(name: str) -> str:
    """Category key for a Product name, or ``UNCATEGORIZED`` when the dictionary has no match."""
    normalized = normalize(name)
    for _, pattern, key in _RULES:
        if pattern.search(normalized):
            return key
    return UNCATEGORIZED
